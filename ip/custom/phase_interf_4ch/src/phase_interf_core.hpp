#ifndef PHASE_INTERF_CORE_HPP
#define PHASE_INTERF_CORE_HPP
// -----------------------------------------------------------------------------
// phase_interf_core.hpp -- tool-independent fixed-point core of the V07
// phase-interferometry block.
//
// This header uses no Xilinx types and no HLS pragmas so that the exact same
// arithmetic can be (a) compiled into the Vitis HLS kernel and (b) compiled and
// run on the host by golden/phase_interf_host_tb.cpp.  That is what makes the
// "host-verified" claim in V07_PHASE_INTERFEROMETRY.md meaningful: the host test
// exercises the production code, not a re-implementation of it.
//
// Conventions (proven numerically by scripts/phase_interf_verify.py):
//
//   X_n = channel n spectrum, A_n = exp(-j*2*pi*f*(p_n . u)/c)
//   S_ab = X_a * conj(X_b)  =>  phase(S_ab) = +2*pi*f*(p_b - p_a).u/c
//
//   baseline 0 : a=0, b=1   azimuth pair   (+y),  uy = +phase*c/(2*pi*f*d)
//   baseline 1 : a=0, b=2   elevation pair (+z),  uz = +phase*c/(2*pi*f*d)
//   baselines 2..5 : (0,3), (1,2), (1,3), (2,3) -- redundant, for WPI weighting
//
// Fixed-point formats
//   sample      : int16  (Q1.15 from the channelizer/FFT)
//   calibration : int16 real/imag, Q2.14  (gain up to ~1.999)
//   calibrated  : int20  (Q3.17 after the >>14 rescale, same as
//                         doa_covariance_4ch_v4 so one PS calibration table
//                         serves both blocks)
//   accumulators: int64  (worst case 51 of 64 bits, see below)
//   phase out   : int16  Q3.13 rad  (range +-4.0 rad, LSB = 1.22e-4 rad)
// -----------------------------------------------------------------------------

#include <cstdint>

namespace pir {

constexpr int kChannels   = 4;
constexpr int kBaselines  = 6;
constexpr int kCordicIters = 16;

// Pair table must stay identical to doa_covariance_4ch_v4.cpp ordering.
constexpr int kFirst[kBaselines]  = {0, 0, 0, 1, 1, 2};
constexpr int kSecond[kBaselines] = {1, 2, 3, 2, 3, 3};

struct CalCoefficient {
    std::int16_t re;   // Q2.14
    std::int16_t im;   // Q2.14
};

// atan(2^-i) in Q2.30, i = 0..15.  Generated by
//   round(atan(2^-i) * 2^30)
// (see the unit test: the table is re-derived on the host and compared).
constexpr std::int32_t kAtanQ30[kCordicIters] = {
    843314857, 497837829, 263043837, 133525159, 67021687, 33543516,
    16775851, 8388437, 4194283, 2097149, 1048576, 524288,
    262144, 131072, 65536, 32768
};

inline std::int32_t atan_q30(int index) { return kAtanQ30[index]; }

// ---------------------------------------------------------------------------
// CORDIC vectoring atan2 -> Q3.13 radians.
// Inputs are the (already accumulated) int64 cross-spectrum components.
// Deterministic integer arithmetic: identical results on host and in HLS.
// ---------------------------------------------------------------------------
inline std::int16_t atan2_q13(std::int64_t y_in, std::int64_t x_in) {
    if (x_in == 0 && y_in == 0) {
        return 0;
    }
    // Bring the larger magnitude into [2^28, 2^29) so every intermediate
    // stays inside int32 and the shift-based rotations keep full precision.
    // Scaling by a power of two does not change the angle.
    std::int64_t ax = x_in < 0 ? -x_in : x_in;
    std::int64_t ay = y_in < 0 ? -y_in : y_in;
    std::int64_t big = ax > ay ? ax : ay;
    int shift = 0;
    while (big >= (std::int64_t(1) << 29)) { big >>= 1; ++shift; }
    while (big < (std::int64_t(1) << 28)) { big <<= 1; --shift; }

    std::int32_t x = static_cast<std::int32_t>(
        shift >= 0 ? (x_in >> shift) : (x_in << (-shift)));
    std::int32_t y = static_cast<std::int32_t>(
        shift >= 0 ? (y_in >> shift) : (y_in << (-shift)));

    // CV = pi in Q2.31 (as an int64 constant: pi * 2^31).
    constexpr std::int64_t kPiQ31 = 6746518852LL;

    // Vectoring CORDIC only covers the right half plane, so pre-rotate by 180
    // degrees when x < 0 and remember the half turn in a wider accumulator.
    std::int64_t halfTurn = 0;
    if (x < 0) {
        x = -x;
        y = -y;
        halfTurn = (y_in >= 0) ? kPiQ31 : -kPiQ31;
    }

    std::int32_t z = 0;  // Q2.30, covers +-1.743 rad, no overflow in int32
    for (int i = 0; i < kCordicIters; ++i) {
        const std::int32_t dx = y >> i;
        const std::int32_t dy = x >> i;
        if (y < 0) { x -= dx; y += dy; z -= kAtanQ30[i]; }
        else       { x += dx; y -= dy; z += kAtanQ30[i]; }
    }
    // z is Q2.30, halfTurn is Q2.31: convert both to Q3.13 (>>17 and >>18).
    const std::int64_t angleQ30 = static_cast<std::int64_t>(z) + (halfTurn >> 1);
    return static_cast<std::int16_t>(angleQ30 >> 17);
}

// ---------------------------------------------------------------------------
// Calibration: (xr + j xi) * (cr + j ci), Q2.14 coefficient, >>14 rescale.
// Mirrors doa_covariance_4ch_v4::calibrate exactly.
// ---------------------------------------------------------------------------
inline void calibrate(std::int16_t xr, std::int16_t xi, const CalCoefficient& cal,
                      std::int32_t& yr, std::int32_t& yi) {
    const std::int32_t cr = cal.re;
    const std::int32_t ci = cal.im;
    const std::int64_t re = static_cast<std::int64_t>(xr) * cr - static_cast<std::int64_t>(xi) * ci;
    const std::int64_t im = static_cast<std::int64_t>(xr) * ci + static_cast<std::int64_t>(xi) * cr;
    yr = static_cast<std::int32_t>(re >> 14);
    yi = static_cast<std::int32_t>(im >> 14);
}

// ---------------------------------------------------------------------------
// One frame of accumulators.
// ---------------------------------------------------------------------------
class FrameAccumulator {
public:
    FrameAccumulator() { reset(); }

    void reset() {
        for (int c = 0; c < kChannels; ++c) { power_[c] = 0; }
        for (int p = 0; p < kBaselines; ++p) { crossRe_[p] = 0; crossIm_[p] = 0; }
        beats_ = 0;
    }

    // One SSR lane: four complex samples of the same frequency bin.
    void addLane(const CalCoefficient cal[kChannels],
                 const std::int16_t* sampleReal,
                 const std::int16_t* sampleImag) {
        std::int32_t re[kChannels];
        std::int32_t im[kChannels];
        for (int c = 0; c < kChannels; ++c) {
            calibrate(sampleReal[c], sampleImag[c], cal[c], re[c], im[c]);
            power_[c] += static_cast<std::int64_t>(re[c]) * re[c] +
                         static_cast<std::int64_t>(im[c]) * im[c];
        }
        for (int p = 0; p < kBaselines; ++p) {
            const int a = kFirst[p];
            const int b = kSecond[p];
            // S_ab = X_a * conj(X_b)
            crossRe_[p] += static_cast<std::int64_t>(re[a]) * re[b] +
                           static_cast<std::int64_t>(im[a]) * im[b];
            crossIm_[p] += static_cast<std::int64_t>(im[a]) * re[b] -
                           static_cast<std::int64_t>(re[a]) * im[b];
        }
        ++beats_;
    }

    std::int64_t power(int channel) const { return power_[channel]; }
    std::int64_t crossReal(int baseline) const { return crossRe_[baseline]; }
    std::int64_t crossImag(int baseline) const { return crossIm_[baseline]; }
    std::int64_t beats() const { return beats_; }

    // CORDIC phases for all six baselines.
    void phases(std::int16_t out[kBaselines]) const {
        for (int p = 0; p < kBaselines; ++p) {
            out[p] = atan2_q13(crossIm_[p], crossRe_[p]);
        }
    }

    // Worst-case bit growth for the documented worst-case input, used by the
    // unit test so the int64 width is a checked claim, not an assumption.
    static int worstCaseBits(int frameSamples) {
        // calibrated value magnitude <= 2^19 (Q3.17 of a Q1.15 sample, |g| <= 2)
        int bits = 19 + 19 + 1;                 // product + sum of two products
        int samples = frameSamples > 0 ? frameSamples : 4096;
        while (samples > 1) { bits += 1; samples >>= 1; }
        return bits;
    }

private:
    std::int64_t power_[kChannels];
    std::int64_t crossRe_[kBaselines];
    std::int64_t crossIm_[kBaselines];
    std::int64_t beats_;
};

}  // namespace pir

#endif  // PHASE_INTERF_CORE_HPP

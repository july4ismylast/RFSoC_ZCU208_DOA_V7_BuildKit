#!/usr/bin/env python3
"""Export the §18 modulation model to the R5 firmware, and a vector set to test it.

Two artefacts, both generated (never hand-edited):

  firmware/amc_r5/amc_model.h   the fitted centre, spread, class means and labels
  build/amc/amc_vectors.bin     bursts + the Python features + the true labels

The model is the same procedure as `scripts/modulation_clustering.py`:
six features, nearest class mean, trained over 0-25 dB on 256-symbol bursts.
The seed is fixed so the header and the vectors are reproducible.

Run:  python3 scripts/amc_export.py [--seed N] [--per-class N] [--symbols N]
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import modulation_clustering as mc  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "firmware", "amc_r5", "amc_model.h")
MATLAB_PARAMS = os.path.join(ROOT, "matlab_v7", "amc_model_params.m")
VECTORS = os.path.join(ROOT, "build", "amc", "amc_vectors.bin")
MAGIC = 0x414D4331


def write_header(model, path=HEADER):
    means, centre, spread = model
    lines = [
        "/* GENERATED by scripts/amc_export.py -- do not edit.",
        " *",
        " * The modulation model measured in V07 section 18, in the form the R5",
        " * firmware (firmware/amc_r5/amc.c) and the MATLAB source",
        " * (matlab_v7/classify_modulation.m) both consume. Fitted over 0-25 dB",
        " * with 256-symbol bursts; see section 18.1 for why the training range",
        " * matters more than the feature set.",
        " */",
        "",
        "#ifndef AMC_R5_AMC_MODEL_H",
        "#define AMC_R5_AMC_MODEL_H",
        "",
        "#include \"amc.h\"",
        "",
        "static const char *const AMC_LABELS[AMC_CLASSES] = {"
        + ", ".join('"%s"' % mod for mod in mc.MODS) + "};",
        "",
        "static const float AMC_CENTRE[AMC_FEATURES] = {"]
    lines.append("    " + ", ".join("%.9ff" % value for value in centre) + "};")
    lines.append("")
    lines.append("static const float AMC_SPREAD[AMC_FEATURES] = {")
    lines.append("    " + ", ".join("%.9ff" % value for value in spread) + "};")
    lines.append("")
    lines.append("static const float AMC_MEANS[AMC_CLASSES][AMC_FEATURES] = {")
    for mod in mc.MODS:
        values = means[mod]
        lines.append("    {  /* %s */" % mod)
        lines.append("        " + ", ".join("%.9ff" % v for v in values) + "},")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* AMC_R5_AMC_MODEL_H */")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return path


def write_matlab(model, path=MATLAB_PARAMS):
    """The same constants for the MATLAB source Embedded Coder compiles."""
    means, centre, spread = model

    def column(values):
        return "; ".join("%.9f" % v for v in values)

    def row(values):
        return " ".join("%.9f" % v for v in values)

    lines = [
        "function [centre, spread, means, labels] = amc_model_params()",
        "%AMC_MODEL_PARAMS  The V07 section 18 modulation model, for MATLAB.",
        "%   GENERATED by scripts/amc_export.py -- do not edit.",
        "%   The C side reads firmware/amc_r5/amc_model.h; both come from the",
        "%   same fit, so classify_modulation.m and amc.c cannot drift apart.",
        "",
        "centre = single([" + column(centre) + "]);",
        "",
        "spread = single([" + column(spread) + "]);",
        "",
        "means = single([ ..."]
    for index, mod in enumerate(mc.MODS):
        suffix = " ]);" if index == len(mc.MODS) - 1 else "; ..."
        lines.append("    " + row(means[mod]) + suffix
                     + ("" if index < len(mc.MODS) - 1 else "   % rows: "
                        + ", ".join(mc.MODS)))
    lines += [
        "",
        "labels = {%s};" % ", ".join("'%s'" % mod for mod in mc.MODS),
        "end",
    ]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return path


def write_vectors(model, rng, per_class, symbols, path=VECTORS):
    """Bursts across the SNR range, with the Python features and the truth."""
    bursts, features, truth = [], [], []
    for index, mod in enumerate(mc.MODS):
        for draw in range(per_class):
            snr = float(rng.choice([0.0, 5.0, 10.0, 20.0]))
            burst = mc.modulate(rng, mod, symbols, snr)
            bursts.append(burst)
            features.append(mc.features(burst))
            truth.append(index)
    count = len(bursts)
    n = bursts[0].size
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(struct.pack("<4i", MAGIC, count, n, mc.FEATURES.__len__()))
        for burst in bursts:
            interleaved = np.empty(2 * n, dtype=np.float32)
            interleaved[0::2] = burst.real
            interleaved[1::2] = burst.imag
            handle.write(interleaved.tobytes())
        handle.write(np.array(features, dtype=np.float32).tobytes())
        handle.write(np.array(truth, dtype=np.int32).tobytes())
    return path, count, n


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=20261111)
    parser.add_argument("--per-class", type=int, default=24)
    parser.add_argument("--symbols", type=int, default=256)
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    model, _, _ = (mc.fit(rng), None, None)
    header = write_header(model)
    matlab = write_matlab(model)
    vectors, count, n = write_vectors(model, rng, args.per_class, args.symbols)
    print("model  -> %s" % os.path.relpath(header, ROOT))
    print("matlab -> %s" % os.path.relpath(matlab, ROOT))
    print("vectors-> %s  (%d bursts, %d samples, %d features)"
          % (os.path.relpath(vectors, ROOT), count, n, len(mc.FEATURES)))
    print("classes: %s" % ", ".join(mc.MODS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

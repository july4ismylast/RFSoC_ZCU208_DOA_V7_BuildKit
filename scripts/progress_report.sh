#!/usr/bin/env bash
# Build docs/progress/PROGRESS.md: one table over every stage, from the stamps,
# the logs and the per-stage pages, so the pushed repository shows progress.
#
# Usage: progress_report.sh <build-dir> <stage> [<stage> ...]
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
build="${1:?usage: progress_report.sh <build-dir> [<stage> ...]}"; shift
cd "$root"
stages=("$@")
# Called from run_stage.sh without a list: read the list the Makefile writes.
if ((${#stages[@]} == 0)); then
    manifest="$build/stages.txt"
    [[ -f "$manifest" ]] || { echo "progress_report.sh: no stages and no $manifest" >&2; exit 2; }
    mapfile -t stages < "$manifest"
fi

out="docs/progress/PROGRESS.md"
mkdir -p docs/progress

count_pass=0; count_fail=0; count_old=0; count_none=0
rows=""

for stage_id in "${stages[@]}"; do
    stamp="$build/.stamps/$stage_id.done"
    log="$build/logs/$stage_id.log"
    page="docs/progress/$stage_id.md"
    status="NOT-RUN"; finished="-"; note=""
    if [[ -f "$page" ]]; then
        status="$(sed -n 's/^result: //p' "$page" | head -n 1)"
        finished="$(sed -n 's/^| finished (UTC) | \(.*\) |$/\1/p' "$page" | head -n 1)"
        note="[page](progress/${stage_id}.md)"
    fi
    if [[ -f "$stamp" ]]; then
        [[ "$status" == "NOT-RUN" || -z "$status" ]] && status="PASS"
        if [[ "$finished" == "-" || -z "$finished" ]]; then
            finished="$(sed -n 's/^finished_utc=//p' "$stamp" | tail -n 1)"
        fi
    elif [[ -f "$log" ]]; then
        [[ "$status" == "NOT-RUN" || -z "$status" ]] && status="OLD/FAILED"
        [[ -n "$note" ]] || note="log only"
    fi
    case "$status" in
        PASS)        count_pass=$((count_pass + 1)) ;;
        FAIL|FAILED) count_fail=$((count_fail + 1)) ;;
        OLD/FAILED)  count_old=$((count_old + 1)) ;;
        *)           count_none=$((count_none + 1)) ;;
    esac
    [[ -n "$finished" ]] || finished="-"
    rows+="| \`${stage_id}\` | ${status} | ${finished} | ${note} |"$'\n'
done

{
    echo "# Build progress"
    echo
    echo "<!-- generated by scripts/progress_report.sh; run \`make progress\` -->"
    echo
    echo "Written by \`make progress\` (and by every \`make stepNN_...\` through"
    echo "\`scripts/run_stage.sh\`). The raw logs stay in \`build/logs/\`, which is not"
    echo "tracked; these pages are, so a pushed branch shows what actually ran."
    echo
    echo "Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo
    echo "| | count |"
    echo "|---|---|"
    echo "| PASS | ${count_pass} |"
    echo "| FAIL | $((count_fail + count_old)) |"
    echo "| NOT-RUN | ${count_none} |"
    echo "| stages | ${#stages[@]} |"
    echo
    echo "| stage | status | finished (UTC) | evidence |"
    echo "|---|---|---|---|"
    printf '%s' "$rows"
    echo
    echo "## What PASS means here"
    echo
    echo "PASS means the stage command exited 0 and wrote its stamp; the stage's own"
    echo "log then holds the evidence (csim output, synthesis report, timing, resource"
    echo "use). It does **not** mean a gate closed: a gate needs its own measurement,"
    echo "and the badges in \`docs/diagrams/system_block.png\` follow those gates."
    echo
    echo "## The two MATLABs"
    echo
    echo "| command | MATLAB |"
    echo "|---|---|"
    echo "| preflight, HIL vectors, \`build_amc_r5.m\`, \`CHANNELIZER_FLOW=matlab_hdl\` | the \`matlab\` on \`PATH\` (R2024a) |"
    echo "| \`make mc\`, \`CHANNELIZER_FLOW=model_composer\` (builds the IP) | R2022b, through the Model Composer launcher, in batch mode |"
    echo "| \`make mc-gui\` (only to create/edit the .slx) | the same R2022b, through the same launcher, with the GUI |"
    echo
    echo "See [\`docs/TWO_MATLABS.md\`](../TWO_MATLABS.md)."
} > "$out"

printf 'wrote %s: %d PASS, %d FAIL, %d NOT-RUN of %d stages\n' \
    "$out" "$count_pass" "$((count_fail + count_old))" "$count_none" "${#stages[@]}"

#!/usr/bin/env bash
# Turn the log of one stage into a small markdown page under docs/progress/.
#
# Why: build/logs/*.log is git-ignored (it is large and machine-specific), so a
# pushed branch showed nothing about what had run.  These pages are tracked, so
# "did step05_channelizer run on the ZCU208 host, and what did it say" is
# answerable from the repository alone.
#
# The page is a summary, never a substitute for the log: it keeps the command,
# the timestamps, the result, and the lines that matter, and it names the log
# for the full text.
set -euo pipefail

stage_id=""; log=""; result=""; out=""; build=""
while (($#)); do
    case "$1" in
        --id)     stage_id="$2"; shift 2 ;;
        --log)    log="$2";      shift 2 ;;
        --result) result="$2";   shift 2 ;;
        --out)    out="$2";      shift 2 ;;
        --build)  build="$2";    shift 2 ;;
        *) echo "stage_report.sh: unknown argument $1" >&2; exit 2 ;;
    esac
done
if [[ -z "$stage_id" || -z "$log" || -z "$result" ]]; then
    echo "usage: stage_report.sh --id ID --log LOG --result PASS|FAIL [--out FILE] [--build DIR]" >&2
    exit 2
fi
out="${out:-docs/progress/${stage_id}.md}"
mkdir -p "$(dirname "$out")"

started="$(sed -n 's/^started_utc=//p'  "$log" | head -n 1)"
finished="$(sed -n 's/^finished_utc=//p' "$log" | head -n 1)"
command_line="$(sed -n 's/^command=//p' "$log" | head -n 1)"
[[ -n "$command_line" ]] || command_line="(not recorded)"

duration="-"
if [[ -n "$started" && -n "$finished" ]]; then
    if s="$(date -u -d "$started" +%s 2>/dev/null)" && f="$(date -u -d "$finished" +%s 2>/dev/null)"; then
        duration="$(( f - s )) s"
    fi
fi

total_lines="$(wc -l < "$log" | tr -d ' ')"
error_lines="$(grep -Eic 'error|FAIL|critical warning' "$log" || true)"
[[ -n "$error_lines" ]] || error_lines=0

# The lines a reader wants first: results, errors, timing and utilisation.
key_lines="$(grep -Ev '^(stage|started_utc|finished_utc|command|result)=' "$log" 2>/dev/null \
    | grep -Ei 'PASS|FAIL|ERROR|ERROR:|WARNING:|WNS|WHS|TNS|Slack|Utilization|Slice LUTs|Register|Block RAM|DSP|Timing|synthesis|impl|bitstream|xsa|elapsed|Time \(s\)|result=|Model Composer|MATLAB|release' 2>/dev/null \
    | tail -n 40 || true)"
[[ -n "$key_lines" ]] || key_lines="(no result, error or timing line in the log)"

{
    echo "# \`${stage_id}\`"
    echo
    echo "<!-- generated by scripts/stage_report.sh; do not edit by hand -->"
    echo "result: ${result}"
    echo
    if [[ "$result" == "PASS" ]]; then
        echo "**Result: PASS** — the stamp exists, so the next stage may run."
    else
        echo "**Result: FAIL** — no stamp was written, so nothing downstream moved."
    fi
    echo
    echo "| field | value |"
    echo "|---|---|"
    echo "| stage | \`${stage_id}\` |"
    echo "| result | ${result} |"
    echo "| started (UTC) | ${started:--} |"
    echo "| finished (UTC) | ${finished:--} |"
    echo "| duration | ${duration} |"
    echo "| log lines | ${total_lines} |"
    echo "| error/fail lines | ${error_lines} |"
    if [[ -n "$build" ]]; then
        echo "| full log | \`${build}/logs/${stage_id}.log\` (not in git) |"
    else
        echo "| full log | \`build/logs/${stage_id}.log\` (not in git) |"
    fi
    echo
    echo "## Command"
    echo
    echo '```'
    printf '%s\n' "$command_line" | sed 's/\\ / /g'
    echo '```'
    echo
    echo "## What the log says"
    echo
    echo '```'
    printf '%s\n' "$key_lines"
    echo '```'
    echo
    echo "Regenerate the whole index with \`make progress\`; the numbers above come"
    echo "from the log, not from a hand-written note."
} > "$out"

echo "report: $out"

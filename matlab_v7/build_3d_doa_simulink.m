    'MedianWindowBins',P.Noise.MedianWindowBins,'PowerFloor',P.Spectrum.PowerFloor));
applyProperties(cfar,struct('NumBins',P.PFB.NumBands,'TrainCells',P.CFAR.TrainCells, ...

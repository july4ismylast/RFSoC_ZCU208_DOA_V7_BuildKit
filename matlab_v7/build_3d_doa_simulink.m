applyProperties(selector,struct('MaxClusters',P.Cluster.MaxClusters, ...
    'BW_MinHz',P.Candidate.BW_MinHz,'BW_MaxHz',P.Candidate.BW_MaxHz, ...
    'MinCandidateSNRdB',P.Candidate.MinSNRdB));

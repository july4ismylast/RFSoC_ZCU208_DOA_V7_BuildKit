    add_line(model,displaySources{index},[displayNames{index} '/1'],'autorouting','on');
end

% Timeseries logs used by plot_simulink_results at the end of simulation.
logs={ ...
    'Log_Pos','log_pos','Platform_3D/1'; ...
    'Log_Yaw','log_yaw','Platform_3D/2'; ...
